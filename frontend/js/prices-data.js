export function fmt(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

// Apply the farmer-side filters to a list from the API (also used for the offline copy).
export function filterOffers(offers, f) {
  const out = offers.filter((o) => {
    if (!f.unverified && !o.buyer.verified) return false;
    if (f.crop && o.crop_id !== f.crop) return false;
    if (f.district && o.district !== f.district) return false;
    if (f.maxKm && (o.distance_km == null || o.distance_km > Number(f.maxKm))) return false;
    return true;
  });
  out.sort((a, b) => b.price - a.price);
  const seen = new Set();
  return out.map((o) => {
    const best = !seen.has(o.crop_id) && !o.check.suspicious;
    if (best) seen.add(o.crop_id);
    return { ...o, best };
  });
}

// Which reference the verdict is based on: live mandi price if known, otherwise MSP.
export function verdictBasis(o) {
  return o.reference.mandi ? 'mandi' : (o.reference.msp ? 'msp' : null);
}
